"""Prompt profiles and lightweight intent detection for programming requests."""
from __future__ import annotations

import re

_PATTERNS = {
    "debug": re.compile(
        r"\b(traceback|exception|stack trace|error|bug|nameerror|typeerror|syntaxerror)\b"
        r"|ошибк|не работает|не запускается|падает|почини|исправь.{0,12}(код|ошибк|файл)"
        r"|посмотри.{0,18}(код|ошибк)|разберись с ошибк",
        re.IGNORECASE,
    ),
    # Only classify a message as a request to invent a new exercise when the
    # user actually asks for one. Merely pasting an assignment is not this intent.
    "exercise": re.compile(
        r"(?:дай|предложи|придумай|подкинь|составь).{0,35}(?:задач\w*|упражнен\w*)"
        r"|(?:хочу|нужна|нужен|давай).{0,20}(?:задач\w*|упражнен\w*)"
        r".{0,30}(?:python|программ|цикл|список)"
        r"|потренир|практическ.{0,12}задан|задачк?у? по python",
        re.IGNORECASE,
    ),
    "continue": re.compile(
        r"продолжи|продолжай|дополни|с того места|на основе предыдущего"
        r"|продолжить работу с кодом|давай дальше|продолжи предыдущий",
        re.IGNORECASE,
    ),
    "solve_exercise": re.compile(
        r"\b(?:реши|решить|выполни|помоги решить|давай решим)\b.{0,80}"
        r"(?:задач\w*|упражнен\w*|задан\w*|пример\w*)"
        r"|(?:твоя|ваша|моя)?\s*(?:задача|задание|условие)\s*[:：—-]?\s*"
        r".{0,180}\b(?:написать|посчитать|вычислить|найти|вывести|создать|"
        r"реализовать|сделать|цикл|средн\w*|список)\b"
        r"|\b(?:напиши|написать|сделай|посчитай|вычисли|найди|выведи)\b"
        r".{0,80}\b(?:цикл|средн\w*|список|рост|элемент|сумм\w*)\b",
        re.IGNORECASE,
    ),
    "explain": re.compile(
        r"объясни|разбер[иь]|что делает|что означает|как работает"
        r"|почему.{0,20}(код|ошибк|программ)|расскажи про"
        r"|объясни.{0,20}(код|ошибк|функц)",
        re.IGNORECASE,
    ),
    "write_code": re.compile(
        r"напиши|написать|сгенерируй|реализуй"
        r"|сделай.{0,15}(функц|класс|код|скрипт|пример|цикл)"
        r"|создай.{0,15}(функц|класс|код|скрипт|файл)"
        r"|пример кода|написать код|написать (?:функц|класс|цикл|скрипт)|покажи код",
        re.IGNORECASE,
    ),
}

_INTENT_INSTRUCTIONS = {
    "debug": (
        "Пользователь разбирает ошибку. Сначала назови вероятную причину, затем предложи "
        "конкретное исправление и объясни, как проверить результат. Не выдумывай отсутствующие строки traceback. "
        "Излагай кратко и не пересказывай весь код."
    ),
    "exercise": (
        "Пользователь просит придумать практическое задание. Дай ровно одно короткое задание: "
        "условие и что должно получиться. Не решай его, не расписывай условие по предложениям "
        "и не добавляй длинные подсказки. Предложи прислать попытку на проверку и остановись."
    ),
    "solve_exercise": (
        "Пользователь прислал условие задачи или попросил выполнить учебное задание. "
        "Реши именно поставленную задачу. Сначала дай цельный рабочий код, затем объясни его "
        "в 1–3 коротких предложениях. Не пересказывай условие, не превращай его обратно в задание "
        "и не разбирай каждую фразу по отдельности. Если чего-то не хватает, явно укажи разумное "
        "предположение и всё равно предложи рабочий вариант."
    ),
    "explain": (
        "Пользователь просит объяснение. Объясняй простым языком и кратко; добавляй пример "
        "только если он помогает понять ответ. Подробный разбор по шагам делай только по просьбе."
    ),
    "write_code": (
        "Пользователь просит код. Дай цельный, запускаемый пример с нужными импортами и понятными именами. "
        "После кода добавь не более 1–3 коротких предложений о принципе работы или запуске. "
        "Не повторяй условие и не делай подробный разбор каждой строки без просьбы."
    ),
    "continue": (
        "Продолжи работу с фрагментом, который уже обсуждался в этой переписке. Сохрани выбранный язык, "
        "имена, архитектуру и контекст. Не переписывай весь проект заново без необходимости; покажи именно продолжение."
    ),
}


def detect_programming_intent(text: str) -> str | None:
    """Classify common programming intents without calling a model."""
    text = (text or "").strip()
    if not text:
        return None
    for intent in ("debug", "continue", "exercise", "solve_exercise", "explain", "write_code"):
        if _PATTERNS[intent].search(text):
            return intent
    return None


def build_coding_prompt(text: str, mode: str = "coding") -> str:
    """Return an additional system instruction for the selected assistant profile."""
    mode = (mode or "coding").strip().lower()
    intent = detect_programming_intent(text)
    if mode not in {"general", "coding", "tutor"}:
        mode = "coding"
    if mode == "general" and intent is None:
        return ""
    if mode == "tutor":
        profile = (
            "Профиль: наставник по программированию. Объясняй простым языком, не перегружай ответ. "
            "Предпочитай одну подсказку за раз и не выдавай полное решение учебной задачи без прямой просьбы."
        )
    elif mode == "coding":
        profile = (
            "Профиль: помощник-программист. Помогай с Python, FastAPI, SQL, Kotlin и другими языками. "
            "При изменении кода предпочитай цельные файлы, сохраняй архитектуру и указывай, какие проверки выполнены. "
            "По умолчанию отвечай кратко: результат сначала, затем только нужное пояснение."
        )
    else:
        profile = (
            "Профиль: универсальный ассистент. Отвечай по существу и не разворачивай простой вопрос "
            "в подробный пошаговый разбор без просьбы."
        )
    if intent:
        instruction = _INTENT_INSTRUCTIONS[intent]
        if mode == "tutor" and intent == "solve_exercise":
            instruction = (
                "Пользователь прислал условие учебной задачи. В режиме наставника не выдавай "
                "полный код сразу: дай одну конкретную подсказку и предложи пользователю попробовать. "
                "Полное решение покажи, если пользователь прямо его попросит."
            )
        return f"{profile}\nТип запроса: {intent}. {instruction}"
    return profile
